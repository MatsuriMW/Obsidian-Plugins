var TGInbox = class extends import_obsidian10.Plugin {
  async onload() {
    this.addSettingTab(new TGInboxSettingTab(this.app, this));
    this.addCommands();
    await this.loadSettings();
    if (this.settings.disable_auto_reception) {
      this.addRibbonIcon("send", "Telegram Inbox: Get Updates", () => {
        var _a2;
        (_a2 = this.bot) == null ? void 0 : _a2.getUpdates();
      });
    }
    this.app.workspace.onLayoutReady(() => {
      if (this.settings.run_after_sync) {
        runAfterSync.call(this, () => {
          this.initBot();
        });
      } else {
        this.initBot();
      }
    });
  }
  addCommands() {
    this.addCommand({
      id: "tg-inbox-getupdates",
      name: "Get Updates",
      callback: () => {
        var _a2;
        return (_a2 = this.bot) == null ? void 0 : _a2.getUpdates();
      }
    });
    this.addCommand({
      id: "tg-inbox-start",
      name: "Start Telegram Bot",
      callback: () => this.startBot()
    });
    this.addCommand({
      id: "tg-inbox-stop",
      name: "Stop Telegram Bot",
      callback: () => this.stopBot()
    });
  }
  async getBotInfo() {
    if (this.bot) {
      return this.bot.bot.api.getMe();
    }
    return null;
  }
  async onunload() {
    this.stopBot();
    console.log("telegram inbox unloaded");
  }
  async loadSettings() {
    this.settings = Object.assign({}, DEFAULT_SETTINGS, await this.loadData());
  }
  async saveSettings() {
    await this.saveData(this.settings);
  }
  async initBot() {
    try {
      if (!this.settings.token) {
        new import_obsidian10.Notice("Telegram bot token not set");
        return;
      }
      await this.stopBot();
      this.bot = new TelegramBot(this.app.vault, this.settings);
      if (!this.settings.disable_auto_reception) {
        this.startBot();
      }
    } catch (error) {
      console.error("Error launching bot:", error);
      new import_obsidian10.Notice("Error launching bot");
      this.bot = null;
    }
  }
  async startBot() {
    new import_obsidian10.Notice("Telegram bot starting");
    if (this.bot) {
      this.bot.start();
    }
  }
  async stopBot() {
    try {
      if (this.bot) {
        await this.bot.bot.stop();
        console.log("bot stopped");
        new import_obsidian10.Notice("Telegram bot stopped");
      }
    } catch (error) {
      console.error("Error stopping bot:", error);
    }
  }
};
